package org.cbi.orbitalis.neoforge.mixin;

import net.minecraft.client.multiplayer.ClientPacketListener;
import net.minecraft.network.protocol.game.ClientboundRespawnPacket;
import org.cbi.orbitalis.minecraft.client.space.FlightTransitionView;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/** Observe the native destination on its client thread before the old level is replaced. */
@Mixin(ClientPacketListener.class)
public abstract class FlightTransitionPacketMixin {
    @Inject(method = "handleRespawn", at = @At(value = "INVOKE", target = "Lnet/minecraft/network/protocol/PacketUtils;ensureRunningOnSameThread(Lnet/minecraft/network/protocol/Packet;Lnet/minecraft/network/PacketListener;Lnet/minecraft/util/thread/BlockableEventLoop;)V", shift = At.Shift.AFTER))
    private void orbitalis$beginView(ClientboundRespawnPacket packet, CallbackInfo callback) {
        FlightTransitionView.INSTANCE.begin(packet.commonPlayerSpawnInfo().dimension());
    }
}
