package org.cbi.orbitalis.neoforge.integration;

import java.util.List;
import java.util.Set;
import org.objectweb.asm.tree.ClassNode;
import org.spongepowered.asm.mixin.extensibility.IMixinConfigPlugin;
import org.spongepowered.asm.mixin.extensibility.IMixinInfo;
import org.spongepowered.asm.mixin.injection.selectors.TargetSelector;

/** Register the bounded selector needed to adapt Sable's optional injected fluid guard. */
public final class OrbitalisMixinPlugin implements IMixinConfigPlugin {
    public void onLoad(String mixinPackage) { TargetSelector.register(SableFluidGuardSelector.class, "orbitalis"); }
    public String getRefMapperConfig() { return null; }
    public boolean shouldApplyMixin(String targetClassName, String mixinClassName) { return true; }
    public void acceptTargets(Set<String> mine, Set<String> others) {}
    public List<String> getMixins() { return null; }
    public void preApply(String target, ClassNode node, String mixin, IMixinInfo info) {}
    public void postApply(String target, ClassNode node, String mixin, IMixinInfo info) {}
}
