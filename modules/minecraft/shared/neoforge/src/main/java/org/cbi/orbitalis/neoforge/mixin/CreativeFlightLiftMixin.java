package org.cbi.orbitalis.neoforge.mixin;

import com.llamalad7.mixinextras.injector.wrapoperation.Operation;
import com.llamalad7.mixinextras.injector.wrapoperation.WrapOperation;
import net.minecraft.client.player.LocalPlayer;
import net.minecraft.world.phys.Vec3;
import org.cbi.orbitalis.minecraft.client.space.PlayerApproachView;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;

@Mixin(LocalPlayer.class)
public abstract class CreativeFlightLiftMixin {
    @WrapOperation(method = "aiStep", at = @At(value = "INVOKE", target = "Lnet/minecraft/world/phys/Vec3;add(DDD)Lnet/minecraft/world/phys/Vec3;"))
    private Vec3 orbitalisCreativeLift(Vec3 velocity, double x, double y, double z, Operation<Vec3> original) {
        if (x != 0.0 || z != 0.0) return original.call(velocity, x, y, z);
        return velocity.add(PlayerApproachView.creativeLift((LocalPlayer) (Object) this, y));
    }
}
